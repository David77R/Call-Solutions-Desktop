function findEntry(key, dict) {
  if (dict[key]) return dict[key];
  for (const [service, entry] of Object.entries(dict)) {
    if (key.startsWith(service) && entry) return entry;
  }
  for (const [service, entry] of Object.entries(dict)) {
    if (key.includes(service) && entry) return entry;
  }
  return null;
}

export function getServiceDescription(descriptions, name, companySlug, lang = 'es') {
  if (!name) return null;
  const key = name.trim().toLowerCase();
  const byCompany = descriptions.byCompany || {};
  const global = descriptions.global || {};

  if (companySlug && byCompany[companySlug]) {
    const override = findEntry(key, byCompany[companySlug]);
    if (override) return override[lang] || override.es || override.en || null;
  }

  const found = findEntry(key, global);
  return found ? found[lang] || found.es || found.en || null : null;
}
